//! A 5 x 7 pixel font for the display, drawn for this firmware.
//!
//! Each glyph is seven rows of five pixels; in a row byte, bit 4 is the
//! leftmost pixel. Characters from space (0x20) to underscore (0x5F) are
//! drawn; lower-case letters are shown as capitals and anything else as `?`.
