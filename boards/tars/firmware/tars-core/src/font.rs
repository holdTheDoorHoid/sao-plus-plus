/// The seven pixel rows of `c` (bit 4 = leftmost pixel).
pub fn glyph(c: char) -> &'static [u8; 7] {
    let c = c.to_ascii_uppercase();
    let code = c as u32;
    if (FIRST as u32..FIRST as u32 + GLYPHS.len() as u32).contains(&code) {
        &GLYPHS[(code - FIRST as u32) as usize]
    } else {
        &GLYPHS[(b'?' - FIRST) as usize]
    }
}

/// Is pixel (x, y) of `c` set? x in 0..5, y in 0..7.
pub fn pixel(c: char, x: i32, y: i32) -> bool {
    if !(0..GLYPH_W).contains(&x) || !(0..GLYPH_H).contains(&y) {
        return false;
    }
    glyph(c)[y as usize] & (0x10 >> x) != 0
}

/// Width in pixels of `text` at `scale`, without the trailing spacing column.
pub fn text_width(text: &str, scale: i32) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 { 0 } else { (n * CELL_W - 1) * scale }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_fit_in_five_bits() {
        for g in GLYPHS.iter() {
            for r in g {
                assert!(*r < 0x20);
            }
        }
    }

    #[test]
    fn every_printable_glyph_but_space_has_ink() {
        for (i, g) in GLYPHS.iter().enumerate().skip(1) {
            assert!(g.iter().any(|r| *r != 0), "glyph {} is blank", i);
        }
    }

    #[test]
    fn lower_case_shows_as_capitals_and_unknown_as_question_mark() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('~'), glyph('?'));
        assert_eq!(glyph('é'), glyph('?'));
    }

    #[test]
    fn letter_t_is_a_bar_and_a_stem() {
        for x in 0..5 {
            assert!(pixel('T', x, 0));
        }
        for y in 1..7 {
            assert!(pixel('T', 2, y));
            assert!(!pixel('T', 0, y));
        }
        assert!(!pixel('T', 5, 0));
    }

    #[test]
    fn widths() {
        assert_eq!(text_width("", 1), 0);
        assert_eq!(text_width("A", 1), 5);
        assert_eq!(text_width("TARS", 2), (4 * 6 - 1) * 2);
    }
}
