#!/usr/bin/env python3
"""Generate donut-core/src/led_table.rs from ../hardware/matrix.json.

Run from anywhere:   python3 gen_led_table.py

The firmware never reads matrix.json at run time; it uses the Rust table this
script writes. A host test (`cargo test` in donut-core, test
`led_table_matches_matrix_json`) re-reads matrix.json and checks every field of
every entry, so a stale or hand-edited table fails the tests.

Units in the table are integers so the firmware needs no floating point:
positions in micrometres, angles in whole degrees (0..359; matrix.json writes
3 o'clock as 360, the table writes it as 0).
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / "hardware" / "matrix.json"
OUT = HERE / "donut-core" / "src" / "led_table.rs"


def um(mm):
    return int(round(mm * 1000))


def main():
    data = json.loads(SRC.read_text())
    leds = data["leds"]
    assert len(leds) == 144, len(leds)
    lines = [
        "// @generated by ../../gen_led_table.py from ../../../hardware/matrix.json.",
        "// Do not edit by hand: change matrix.json and re-run the script.",
        "// The test `led_table_matches_matrix_json` checks this table against the JSON.",
        "",
        "use crate::leds::Led;",
        "",
        "/// Every LED, in the maker's order: index 0..=71 are DA1..DA72 (his LED1..LED72),",
        "/// 72..=143 are DB1..DB72 (his LED73..LED144).",
        "#[rustfmt::skip]",
        "pub const LEDS: [Led; 144] = [",
    ]
    for i, l in enumerate(leds):
        expect = f"D{'A' if i < 72 else 'B'}{i % 72 + 1}"
        assert l["ref"] == expect, (l["ref"], expect)
        angle = int(round(l["angle_deg"])) % 360
        assert abs(l["angle_deg"] - round(l["angle_deg"])) < 1e-9, l
        lines.append(
            f'    Led {{ name: "{l["ref"]}", x_um: {um(l["x_mm"])}, y_um: {um(l["y_mm"])}, '
            f'r_um: {um(l["r_mm"])}, angle_deg: {angle}, '
            f'index_cathode_row: {l["frame"]["index"]}, '
            f'index_anode_row: {l["frame_if_row_is_anode"]["index"]} }},'
        )
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(leds)} LEDs)")


if __name__ == "__main__":
    main()
